"""Oura Ring data source, via Oura's official Cloud API v2
(https://cloud.ouraring.com/v2/docs).

Auth is a single long-lived Personal Access Token, generated by the user at
cloud.ouraring.com/personal-access-tokens and sent as a plain
`Authorization: Bearer <token>` header — same shape as Garmin's Personal API
key (see sources/garmin.py), and deliberately NOT wired through Home
Assistant's Application Credentials/OAuth2 system (used for Strava): that
system keys registered OAuth implementations by auth_domain/client_id, with
no field a user-facing "which provider is this credential for" choice could
hang off within a single integration domain, and Oura's PAT flow needs none
of OAuth2's machinery (no client_id/secret, no authorization redirect, no
refresh token) anyway, so a plain config-flow text field matches both the
simplest path and the only one that's actually unambiguous for a user to set
up correctly.

All fields/endpoints below were confirmed directly against Oura's own
published OpenAPI spec (fetched from cloud.ouraring.com/v2/static/json/
openapi-1.43.json, the current version linked from cloud.ouraring.com/v2/docs
as of 2026-10-31) — not guessed or inferred from third-party wrapper
libraries. Notable, easy-to-get-wrong findings from that spec:

- GET /v2/usercollection/daily_sleep (PublicDailySleep) does NOT carry sleep
  duration or stage breakdown — its only fields are id/day/score/
  contributors/timestamp. Actual sleep durations (total/deep/REM/light/
  awake, in seconds), average heart rate and HRV during sleep, and sleep
  efficiency all live on the separate GET /v2/usercollection/sleep endpoint
  (PublicModifiedSleepModel) instead — a real nightly SLEEP SESSION record,
  distinct from the daily SCORE document. Both are fetched here.
- Oura has no standalone "resting heart rate" reading anywhere in the API —
  only a resting_heart_rate READINESS CONTRIBUTOR (a 1-100 contribution
  score, not a bpm value — PublicReadinessContributors.resting_heart_rate).
  The closest real bpm figure is the sleep session's lowest_heart_rate,
  used here for DailySummary.resting_heart_rate (labeled accordingly below).
- PublicWorkout.activity is a plain, unconstrained string in Oura's spec (no
  enum list, unlike e.g. intensity/source on the same object) — Oura does
  not publish a closed set of activity-type values, so _map_activity_type
  below matches on substrings of whatever string comes back rather than an
  exhaustive lookup table, and genuinely unrecognized values fall through to
  ActivityType.OTHER rather than erroring.
- Workouts carry no per-km/lap data at all (no splits endpoint, no lap
  field on PublicWorkout) — Activity.splits is always None for this source,
  same meaning as for Strava/Coros (not fetched/not available).
- Pagination is cursor-based: list endpoints return {"data": [...],
  "next_token": "..."}; next_token is None/absent once the final page has
  been returned.
"""
from __future__ import annotations

import logging
from datetime import date, datetime
from typing import Any

import aiohttp
from homeassistant.core import HomeAssistant
from homeassistant.helpers.aiohttp_client import async_get_clientsession

from ..models import Activity, ActivityType, DailySummary, WorkoutData
from .base import (
    WorkoutSource,
    WorkoutSourceAuthError,
    WorkoutSourceError,
    WorkoutSourceRateLimitedError,
)

_LOGGER = logging.getLogger(__name__)

_API_BASE = "https://api.ouraring.com/v2"

# Oura's PublicWorkout.activity is a free-text string with no published enum
# (confirmed via its OpenAPI schema — see module docstring), so this matches
# on substrings of whatever comes back rather than an exhaustive lookup.
# Order matters: checked top-to-bottom, first match wins.
_ACTIVITY_TYPE_SUBSTRING_MAP: tuple[tuple[str, ActivityType], ...] = (
    ("running", ActivityType.RUNNING),
    ("run", ActivityType.RUNNING),
    ("cycling", ActivityType.CYCLING),
    ("biking", ActivityType.CYCLING),
    ("bike", ActivityType.CYCLING),
    ("swimming", ActivityType.SWIMMING),
    ("swim", ActivityType.SWIMMING),
    ("walking", ActivityType.WALKING),
    ("walk", ActivityType.WALKING),
    ("hiking", ActivityType.HIKING),
    ("hike", ActivityType.HIKING),
    ("yoga", ActivityType.YOGA),
    ("strength", ActivityType.STRENGTH_TRAINING),
    ("weight", ActivityType.STRENGTH_TRAINING),
)


def _map_activity_type(oura_activity: str | None) -> ActivityType:
    if not oura_activity:
        return ActivityType.OTHER
    lowered = oura_activity.lower()
    for substring, activity_type in _ACTIVITY_TYPE_SUBSTRING_MAP:
        if substring in lowered:
            return activity_type
    return ActivityType.OTHER


class OuraSource(WorkoutSource):
    """Fetches daily scores, sleep detail, and workouts from Oura's Cloud API v2."""

    key = "oura"
    # Oura's documented limit is 5,000 requests per 5-minute window per
    # token (confirmed via Oura's own docs) — far more generous than any
    # other source here, so no special backfill pacing is needed; this just
    # keeps the same conservative default every other integration-wide
    # unofficial/undocumented source uses, since there's no benefit to
    # being more aggressive for a one-call-per-chunk backfill anyway.
    backfill_chunk_pause_seconds = 5.0

    def __init__(self, hass: HomeAssistant, access_token: str) -> None:
        self._hass = hass
        self._access_token = access_token

    def _client(self) -> aiohttp.ClientSession:
        return async_get_clientsession(self._hass)

    async def async_authenticate(self) -> None:
        # No separate login/token-exchange step exists for a Personal Access
        # Token (see module docstring) — this just validates the token
        # works by touching the cheapest authenticated endpoint.
        await self._request("/usercollection/personal_info")

    async def async_fetch(self, target_day: date) -> WorkoutData:
        activities = await self.async_fetch_activities_range(target_day, target_day)
        daily_summary = await self._fetch_daily_summary(target_day)
        return WorkoutData(activities=activities, daily_summary=daily_summary)

    async def async_fetch_activities_range(
        self, start_day: date, end_day: date
    ) -> list[Activity]:
        raw_workouts = await self._list_all(
            "/usercollection/workout", start_day, end_day
        )
        return [self._parse_activity(item) for item in raw_workouts]

    async def _fetch_daily_summary(self, day: date) -> DailySummary | None:
        """Combine daily_readiness (score), daily_sleep (score), daily_activity
        (score + steps + calories), and sleep (duration/stage/HR/HRV detail)
        into one DailySummary for this day.

        Each of these is fetched independently and is allowed to come back
        empty (Oura simply won't have, say, a sleep record for a day the
        ring wasn't worn overnight) — this returns None only if ALL of them
        are empty, since a partially-populated DailySummary is still useful,
        same as every other source's _fetch_daily_summary treats partial data.
        """
        readiness_items = await self._list_all("/usercollection/daily_readiness", day, day)
        sleep_score_items = await self._list_all("/usercollection/daily_sleep", day, day)
        activity_items = await self._list_all("/usercollection/daily_activity", day, day)
        sleep_session_items = await self._list_all("/usercollection/sleep", day, day)

        if not (readiness_items or sleep_score_items or activity_items or sleep_session_items):
            return None

        readiness = readiness_items[0] if readiness_items else {}
        sleep_score_doc = sleep_score_items[0] if sleep_score_items else {}
        activity = activity_items[0] if activity_items else {}
        # A day can have more than one sleep session (e.g. a nap plus the
        # main night's sleep) — the longest total_sleep_duration is treated
        # as "the" night's sleep for this day's summary, matching what
        # Oura's own app highlights as the day's main sleep.
        sleep_session = max(
            sleep_session_items,
            key=lambda item: item.get("total_sleep_duration") or 0,
            default={},
        )

        return DailySummary(
            source=self.key,
            day=day,
            steps=activity.get("steps"),
            active_calories=activity.get("active_calories"),
            activity_score=activity.get("score"),
            readiness_score=readiness.get("score"),
            sleep_score=sleep_score_doc.get("score"),
            sleep_seconds=sleep_session.get("total_sleep_duration"),
            deep_sleep_seconds=sleep_session.get("deep_sleep_duration"),
            rem_sleep_seconds=sleep_session.get("rem_sleep_duration"),
            light_sleep_seconds=sleep_session.get("light_sleep_duration"),
            # See module docstring: Oura has no standalone resting-heart-rate
            # reading; lowest_heart_rate during sleep is the closest real
            # bpm figure the API provides.
            resting_heart_rate=sleep_session.get("lowest_heart_rate"),
            oura_avg_hrv=sleep_session.get("average_hrv"),
        )

    async def _list_all(
        self, path: str, start_day: date, end_day: date
    ) -> list[dict[str, Any]]:
        """GET one usercollection endpoint across its full date range,
        following next_token until Oura reports no more pages.
        """
        results: list[dict[str, Any]] = []
        next_token: str | None = None
        while True:
            params: dict[str, Any] = {
                "start_date": start_day.isoformat(),
                "end_date": end_day.isoformat(),
            }
            if next_token:
                params["next_token"] = next_token
            response = await self._request(path, params=params)
            results.extend(response.get("data", []))
            next_token = response.get("next_token")
            if not next_token:
                break
        return results

    async def _request(
        self, path: str, params: dict[str, Any] | None = None
    ) -> dict[str, Any]:
        try:
            async with self._client().get(
                f"{_API_BASE}{path}",
                headers={"Authorization": f"Bearer {self._access_token}"},
                params=params,
            ) as resp:
                if resp.status == 401:
                    raise WorkoutSourceAuthError(
                        "Oura Personal Access Token was rejected — it may have been "
                        "revoked. Generate a new token at "
                        "cloud.ouraring.com/personal-access-tokens and reconnect this "
                        "integration."
                    )
                if resp.status == 429:
                    raise WorkoutSourceRateLimitedError("Oura API rate limited us")
                resp.raise_for_status()
                return await resp.json()
        except aiohttp.ClientError as err:
            raise WorkoutSourceError(f"Error communicating with Oura: {err}") from err

    def _parse_activity(self, item: dict[str, Any]) -> Activity:
        start = datetime.fromisoformat(item["start_datetime"])
        end = datetime.fromisoformat(item["end_datetime"])
        return Activity(
            source=self.key,
            source_id=item["id"],
            activity_type=_map_activity_type(item.get("activity")),
            start=start,
            duration_seconds=(end - start).total_seconds(),
            distance_meters=item.get("distance"),
            calories=item.get("calories"),
            name=item.get("label") or item.get("activity"),
            # No splits/laps anywhere in Oura's workout API — see module
            # docstring. Left as None (not fetched/not available), same
            # convention as every other source without this data.
        )

    @classmethod
    def config_schema_fields(cls) -> dict[str, Any]:
        return {"access_token": str}
